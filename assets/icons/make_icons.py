def rows(grid: str) -> list[str]:
    r = grid.strip("\n").split("\n")
    assert len(r) == 16 and all(len(x) == 16 for x in r), [len(x) for x in r]
    assert set("".join(r)) <= set(PALETTE) | {"."}
    return r


def svg(grid: str) -> str:
    rects = "".join(f'<rect x="{x}" y="{y}" width="1" height="1" fill="{PALETTE[c]}"/>'
                    for y, row in enumerate(rows(grid)) for x, c in enumerate(row) if c != ".")
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" shape-rendering="crispEdges">{rects}</svg>\n'


def png(grid: str) -> Image.Image:
    img = Image.new("RGBA", (16, 16))
    for y, row in enumerate(rows(grid)):
        for x, c in enumerate(row):
            if c != ".":
                img.putpixel((x, y), ImageColor.getrgb(PALETTE[c]))
    return img


if __name__ == "__main__":
    sheet = Image.new("RGBA", (len(ICONS) * 160, 160), "#f6f8fa")
    for i, (name, grid) in enumerate(ICONS.items()):
        (OUT / f"{name}.svg").write_text(svg(grid))
        big = png(grid).resize((16 * SCALE, 16 * SCALE), Image.NEAREST)
        big.save(OUT / f"{name}.png")
        sheet.alpha_composite(big, (i * 160 + 16, 16))
    sheet.save(OUT / "sheet.png")
    png(ICONS["alfred"]).resize((64, 64), Image.NEAREST).save(OUT / "favicon.ico", sizes=[(16, 16), (32, 32), (64, 64)])
